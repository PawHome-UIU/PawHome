package com.pawhome.backend.billing;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;

/**
 * One line on a bill besides the nights. Maps `billing_slip_items` from V15.
 *
 * WHAT THIS IS FOR: the owner collects early and owes for the antibiotics, the
 * extra bag of their own brand of food, and a bath. V13 left
 * billing_slips.total free-form -- with deliberately NO CHECK tying it to
 * units * unit_rate -- precisely so this could arrive without a rewrite.
 *
 * THE BASE CHARGE IS NOT ONE OF THESE. Nights boarded, or one subscribed
 * month, stays on billing_slips as units / unit_rate. Making everything a line
 * would be the textbook invoice shape and would also mean rewriting the
 * issuing path, the printable page and the three unique keys that already make
 * issuing idempotent -- for a bill that reads the same either way.
 *
 * line_total IS READ-ONLY FROM JAVA because the database computes it:
 * ROUND(quantity * unit_price, 2), STORED. A line has no reason to say
 * anything else -- unlike the slip's total, which must stay free enough to
 * express a goodwill discount -- so the arithmetic lives where it cannot drift
 * from the two numbers beside it. MySQL rejects an INSERT that tries to
 * supply it, which is the point.
 */
@Entity
@Table(name = "billing_slip_items")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class BillingSlipItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "slip_id", nullable = false)
    private Long slipId;

    /**
     * Free text, and not an enum. The day somebody needs "replacement collar"
     * and the enum has no value for it, the charge goes in as OTHER and the
     * line stops explaining itself to the person paying it.
     */
    @Column(nullable = false, length = 120)
    private String description;

    /** DECIMAL: half a bag of food and 2.5 hours of grooming are real. */
    @Column(nullable = false, precision = 8, scale = 2)
    @Builder.Default
    private BigDecimal quantity = BigDecimal.ONE;

    @Column(name = "unit_price", nullable = false, precision = 10, scale = 2)
    private BigDecimal unitPrice;

    /** Generated by the database. Never written from here. */
    @Column(name = "line_total", insertable = false, updatable = false,
            precision = 10, scale = 2)
    private BigDecimal lineTotal;

    /** The order the staff member typed them in. Without it the bill reorders itself. */
    @Column(name = "sort_order", nullable = false)
    @Builder.Default
    private short sortOrder = 0;
}
