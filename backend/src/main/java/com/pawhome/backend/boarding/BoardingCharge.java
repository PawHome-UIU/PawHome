package com.pawhome.backend.boarding;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * One expense run up during a stay. Maps `boarding_charges` from V17.
 *
 * NOT A BillingSlipItem, AND THE DIFFERENCE IS THE LIFECYCLE. This one is
 * ACCRUING: staff add it on Tuesday when the pet has a worming tablet, correct
 * it when they mistype the price, and remove it if the vet visit never
 * happened. Nobody has been billed anything yet.
 *
 * A BillingSlipItem is FROZEN -- a line on an issued bill, and the record of
 * what the customer was actually asked to pay. BoardingService.complete()
 * copies these into those, and after that the copy is the one that counts.
 *
 * WHY NOT ONE TABLE WITH A FLAG. Because "has this been billed" is already
 * answerable from the stay: a COMPLETED stay has exactly one slip
 * (uq_slip_boarding), so a flag here would be a second copy of that fact, free
 * to disagree with it. Worse, a shared row would mean correcting a charge after
 * the bill was printed silently changed what the customer owed.
 *
 * THE SAME REASONING PRICES THE REST OF THIS MODULE. boarding_requests
 * .daily_rate is copied off the shelter so a price rise cannot reprice a booked
 * stay; billing_slips.unit_rate is copied again so it cannot reprice an issued
 * bill. Money that a customer has been quoted stops moving.
 *
 * line_total IS READ-ONLY FROM JAVA, as on BillingSlipItem: the database
 * computes ROUND(quantity * unit_price, 2) STORED, so the arithmetic cannot
 * drift from the two numbers beside it. MySQL rejects an INSERT that supplies
 * it, which is the point.
 */
@Entity
@Table(name = "boarding_charges")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class BoardingCharge {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "boarding_id", nullable = false)
    private Long boardingId;

    /**
     * Free text, and not an enum -- the same call BillingSlipItem makes. The
     * description is what gets printed on the slip and read at the counter, so
     * the day somebody needs "replacement collar" it has to be sayable.
     */
    @Column(nullable = false, length = 120)
    private String description;

    /** DECIMAL: half a bag of food and 2.5 hours of grooming are real. */
    @Column(nullable = false, precision = 8, scale = 2)
    @Builder.Default
    private BigDecimal quantity = BigDecimal.ONE;

    @Column(name = "unit_price", nullable = false, precision = 10, scale = 2)
    private BigDecimal unitPrice;

    /** Generated by the database. Never written from here. */
    @Column(name = "line_total", insertable = false, updatable = false,
            precision = 10, scale = 2)
    private BigDecimal lineTotal;

    /**
     * Nullable, because fk_charges_user is ON DELETE SET NULL. A staff member
     * must not become undeletable for having fed a dog, and the charge is
     * still valid without a name against it.
     */
    @Column(name = "added_by")
    private Long addedBy;

    @Column(name = "added_at", nullable = false, insertable = false, updatable = false)
    private LocalDateTime addedAt;
}
