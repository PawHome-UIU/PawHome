import { useEffect, useMemo, useState } from "react";
import {
  FiFile, FiDownload, FiFileText, FiHome, FiCalendar, FiUser, FiTrash2, FiAlertCircle,
} from "react-icons/fi";
import AdminLayout from "../../components/admin/AdminLayout";
import Card from "../../components/ui/Card";
import Button from "../../components/ui/Button";
import Modal from "../../components/ui/Modal";
import Dropdown from "../../components/ui/Dropdown";
import GenerateReportModal from "../../components/admin/GenerateReportModal";
import api from "../../api/client";
import { apiError } from "../../lib/apiError";

/**
 * The report library.
 *
 * WHAT CHANGED. This page listed four invented PDFs from data/admin.js --
 * "Quarterly_Impact_Q3.pdf", generated by "Sarah Jenkins", 412 KB -- and its
 * Download button was a Button with no onClick. Generate opened a dialog that
 * threw its result away and showed "Report queued", which was true of nothing.
 * The `reports` table had existed since V1 with no row ever written to it.
 *
 * A LIBRARY, NOT A DOWNLOAD BUTTON. The table stores file_path and generated_by
 * precisely so a report outlives the session that made it -- the quarterly
 * summary a coordinator built in October is the one the board asks for in
 * January, and it should still be here.
 *
 * THE DOWNLOAD GOES THROUGH AXIOS, NOT AN <a href>. A report holds adopters'
 * names, emails and fees, so it is served from /api/v1/admin/** behind the
 * admin gate rather than from the public /files route -- which means the
 * request needs the bearer token, which a plain link cannot send. The bytes
 * come back as a blob and are handed to the browser as a temporary object URL.
 */

const SIZE = (bytes) => {
  if (bytes < 0) return "file missing";
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
};

const when = (iso) =>
  iso ? new Date(iso).toLocaleString(undefined,
    { month: "short", day: "numeric", year: "numeric", hour: "numeric", minute: "2-digit" }) : "";

const day = (iso) =>
  iso ? new Date(`${iso}T00:00:00`).toLocaleDateString(undefined,
    { month: "short", day: "numeric", year: "numeric" }) : "";

export default function ReportsPage() {
  const [types, setTypes] = useState([]);
  const [reports, setReports] = useState([]);
  const [filter, setFilter] = useState(null);
  const [genOpen, setGenOpen] = useState(false);
  const [deleting, setDeleting] = useState(null);
  const [busyId, setBusyId] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(true);

  // An async IIFE rather than a useCallback the effect then calls: every
  // setState below sits after an await, which is what keeps this out of
  // react-hooks/set-state-in-effect. Calling a function that happens to be
  // async trips the rule regardless, because the linter cannot see inside it.
  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const [typeRes, listRes] = await Promise.all([
          api.get("/admin/reports/types"),
          api.get("/admin/reports"),
        ]);
        if (cancelled) return;
        setTypes(typeRes.data);
        setReports(listRes.data);
        setError("");
      } catch (err) {
        if (!cancelled) setError(apiError(err, "The report library could not be loaded."));
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => { cancelled = true; };
  }, []);

  /**
   * Fetch the bytes with the token attached, then hand them to the browser.
   *
   * The object URL is revoked immediately after the click. It is not needed
   * once the download has started, and leaving it alive pins the whole file
   * in memory for as long as the tab is open.
   */
  async function download(report) {
    setBusyId(report.id);
    try {
      const { data } = await api.get(`/admin/reports/${report.id}/download`,
        { responseType: "blob" });
      const url = URL.createObjectURL(data);
      const a = document.createElement("a");
      a.href = url;
      a.download = report.fileName;
      document.body.appendChild(a);
      a.click();
      a.remove();
      URL.revokeObjectURL(url);
    } catch (err) {
      // A blob-typed error body is a Blob, not JSON, so apiError cannot read
      // the server's sentence out of it. Saying so plainly beats "[object Blob]".
      setError(err.response?.status === 404
        ? "That report's file is no longer on the server. Generate it again."
        : apiError(err, "That report could not be downloaded."));
    } finally {
      setBusyId(null);
    }
  }

  async function remove() {
    setBusyId(deleting.id);
    try {
      await api.delete(`/admin/reports/${deleting.id}`);
      setReports((list) => list.filter((r) => r.id !== deleting.id));
      setDeleting(null);
    } catch (err) {
      setError(apiError(err, "That report could not be removed."));
    } finally {
      setBusyId(null);
    }
  }

  const rows = useMemo(
    () => (filter ? reports.filter((r) => r.typeLabel === filter) : reports),
    [filter, reports]
  );

  return (
    <AdminLayout
      title="Reports"
      subtitle="Every report generated across the network, kept for whoever needs it next."
      actions={
        <>
          <Dropdown
            variant="bar"
            align="right"
            label="All types"
            anyLabel="All types"
            value={filter}
            onChange={setFilter}
            options={types.map((t) => t.label)}
          />
          <Button size="sm" onClick={() => setGenOpen(true)}>
            <FiFile className="h-4 w-4" /> Generate Report
          </Button>
        </>
      }
    >
      {error && (
        <Card className="mb-5 flex items-start gap-3 border-pw-danger/40 bg-rose-50/60 p-4">
          <FiAlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-pw-danger" />
          <p className="text-sm text-pw-danger">{error}</p>
        </Card>
      )}

      <div className="grid gap-5 sm:grid-cols-2 xl:grid-cols-4">
        {types.map((t) => {
          const n = reports.filter((r) => r.reportType === t.value).length;
          return (
            <Card key={t.value} className="flex flex-col p-6">
              <span className="flex h-10 w-10 items-center justify-center rounded-full bg-pw-input text-pw-button">
                <FiFileText className="h-[18px] w-[18px]" />
              </span>
              <h2 className="mt-4 text-[15px] font-semibold text-pw-ink">{t.label}</h2>
              <p className="mt-1.5 flex-1 text-sm leading-relaxed text-pw-muted">{t.blurb}</p>
              <p className="mt-4 border-t border-pw-stroke/40 pt-3 text-sm text-pw-muted">
                {n === 0 ? "None yet" : `${n} in the library`}
              </p>
            </Card>
          );
        })}
      </div>

      <section className="mt-10">
        <h2 className="text-lg font-semibold">Report library</h2>

        {loading ? (
          <p className="py-16 text-center text-sm text-pw-muted">Loading…</p>
        ) : rows.length === 0 ? (
          <Card className="mt-5 px-6 py-16 text-center">
            <p className="text-[15px] font-medium text-pw-ink">
              {filter ? "No reports of that type yet." : "No reports yet."}
            </p>
            <p className="mt-1.5 text-sm text-pw-muted">
              Generate one and it will be kept here for the rest of the team.
            </p>
          </Card>
        ) : (
          <Card className="mt-5 overflow-hidden">
            <ul className="divide-y divide-pw-stroke/30">
              {rows.map((r) => (
                <li key={r.id} className="flex flex-wrap items-center gap-4 px-5 py-4">
                  <span className="flex h-11 w-11 shrink-0 items-center justify-center rounded-2xl bg-pw-input text-pw-button">
                    <FiFileText className="h-5 w-5" />
                  </span>

                  <div className="min-w-[220px] flex-1">
                    <p className="text-[15px] font-medium text-pw-ink">{r.fileName}</p>
                    <p className="mt-1 flex flex-wrap items-center gap-x-4 gap-y-1 text-sm text-pw-muted">
                      <span className="flex items-center gap-1.5">
                        <FiCalendar className="h-3.5 w-3.5" /> {day(r.dateFrom)} – {day(r.dateTo)}
                      </span>
                      <span className="flex items-center gap-1.5">
                        <FiHome className="h-3.5 w-3.5" />
                        {/* NULL shelter_id is network-wide, and saying so beats
                            an empty cell the reader has to interpret. */}
                        {r.shelterName ?? "All shelters"}
                      </span>
                      <span className="flex items-center gap-1.5">
                        <FiUser className="h-3.5 w-3.5" />
                        {/* NULL generated_by means the account was deleted --
                            fk_reports_author is ON DELETE SET NULL, so the file
                            outlives its author rather than vanishing with them. */}
                        {r.generatedByName ?? "a deleted account"}
                      </span>
                    </p>
                  </div>

                  <div className="text-right">
                    <span className="rounded-pill bg-pw-input px-3 py-1 text-[11px] font-semibold text-pw-button">
                      {r.typeLabel}
                    </span>
                    <p className="mt-1 text-xs text-pw-muted">
                      {when(r.generatedAt)} · {SIZE(r.sizeBytes)}
                    </p>
                  </div>

                  <div className="flex gap-2">
                    <Button variant="outline" size="sm"
                      disabled={busyId === r.id || r.sizeBytes < 0}
                      onClick={() => download(r)}>
                      <FiDownload className="h-4 w-4" />
                      {busyId === r.id ? "Working…" : "Download"}
                    </Button>
                    <Button variant="subtle" size="sm"
                      disabled={busyId === r.id}
                      onClick={() => setDeleting(r)}
                      aria-label={`Remove ${r.fileName}`}>
                      <FiTrash2 className="h-4 w-4" />
                    </Button>
                  </div>
                </li>
              ))}
            </ul>
          </Card>
        )}
      </section>

      <GenerateReportModal
        open={genOpen}
        types={types}
        onClose={() => setGenOpen(false)}
        // The server returns the finished row, so the library updates without
        // a refetch -- and the new report is genuinely there, not "queued".
        onGenerated={(row) => { setGenOpen(false); setReports((list) => [row, ...list]); }}
      />

      <Modal
        open={deleting != null}
        onClose={() => setDeleting(null)}
        title="Remove this report?"
        size="sm"
        footer={
          <>
            <Button variant="outline" onClick={() => setDeleting(null)} disabled={busyId != null}>
              Cancel
            </Button>
            <Button onClick={remove} disabled={busyId != null}>
              {busyId != null ? "Removing…" : "Remove"}
            </Button>
          </>
        }
      >
        <p className="text-[15px] leading-relaxed text-pw-body">
          <span className="font-medium text-pw-ink">{deleting?.fileName}</span> and
          its file are deleted for everyone. Nothing else in the system refers to
          a report, so this is a real delete rather than a status change — but
          the same window can be generated again at any time.
        </p>
      </Modal>
    </AdminLayout>
  );
}
